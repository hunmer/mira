const dict: Record<Locale, Record<string, string>> = { zh, en }

export function parseLocale(tag: string | undefined | null): Locale {
  return String(tag || '').toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/** 初始语言:宿主注入的应用语言 → 浏览器语言 */
export function initialLocale(): Locale {
  if (typeof window !== 'undefined') {
    const host = (window as unknown as { mira?: { app?: { locale?: string } } }).mira
    if (host?.app?.locale) return parseLocale(host.app.locale)
    if (typeof navigator !== 'undefined' && navigator.language) return parseLocale(navigator.language)
  }
  return 'zh'
}

/** 共享单例:包内全部组件共用同一 locale 状态 */
const sharedLocale = ref<Locale>(initialLocale())

/** 宿主切换语言(接受任意 BCP 47 tag,如主窗口 onLocaleChanged 回调值) */
export function setLocale(tag: string | Locale) {
  sharedLocale.value = tag === 'zh' || tag === 'en' ? tag : parseLocale(tag)
}

export function useI18n() {
  const locale = sharedLocale

  function t(key: string, params?: Record<string, unknown>): string {
    const template = dict[locale.value][key] ?? dict.zh[key] ?? key
    if (!params) return template
    return template.replace(/\{(\w+)\}/g, (m, name: string) =>
      name in params ? String(params[name]) : m,
    )
  }

  return { locale, setLocale, t }
}

/** {n} 命名插值(vue-i18n 风格) */
export function interpolate(template: string, params?: Record<string, unknown>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (m, key: string) =>
    key in params ? String(params[key]) : m,
  )
}

/**
 * 内置兜底 t(library 系列组件 t prop 缺省值)。
 * 读取包级单例 locale,宿主未传 t 时文案仍随 setLocale 切换。
 */
export function createLibraryTreeT() {
  const { t } = useI18n()
  return t
}
